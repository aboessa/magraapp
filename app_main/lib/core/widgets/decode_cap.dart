/// سقف فكّ الترميز عند حجم العرض، لا حجم المصدر (`PERF-102`).
///
/// ## الخلط الذي يجعل هذا الملف ضروريًّا
///
/// `width`/`height` على `Image` تحدّدان **التخطيط** ولا تمسّان فكّ الترميز.
/// فصورة 768×1376 مُعطاة `width: 72` تُفكّ في الذاكرة بكامل أبعادها: نحو
/// **4 ميغابايت** لدائرةٍ بعرض 72. و`cacheWidth` وحدها هي التي تُقلّص الفكّ.
///
/// ## المقيس
///
/// أفاتارات الشخصيات: **50 صورة** حتى 768×1376 = **200 ميغابايت** لو عاشت كلّها
/// بكامل أبعادها، وتُعرض في خلايا 72–78 بكسل منطقي. والكواكب: **10 صور** 768×768
/// = 22.5 ميغابايت، في دوائر 58–72 بكسل. على أجهزة أطفال منخفضة الذاكرة هذا سببٌ
/// مباشر لتقطيع التمرير ولإغلاق النظام للتطبيق.
///
/// ## وما لا يُقاس عليه
///
/// السقف بالبكسل **الفيزيائي** لا المنطقي: شاشة 3× تحتاج 216 بكسلًا لخليّة 72،
/// وتمريرُ 72 يُنتج صورةً ضبابية. ولذلك يُقرأ `devicePixelRatio` من السياق ولا
/// يُفترض.
library;

import 'package:flutter/widgets.dart';

/// عدد البكسلات الفيزيائية المقابلة لـ[logicalWidth] في سياق [context].
///
/// تُعيد `null` حين لا يُعرف حجم الحوض — وهو الجواب الصحيح لا الصفر: سقفٌ
/// مُخترَع على حوضٍ مجهول يُنتج صورةً ضبابية في مكانٍ لم يُقَس.
int? decodeCapFor(BuildContext context, double? logicalWidth) {
  if (logicalWidth == null ||
      !logicalWidth.isFinite ||
      logicalWidth <= 0) {
    return null;
  }
  final cap = (logicalWidth * MediaQuery.devicePixelRatioOf(context)).round();
  return cap <= 0 ? null : cap;
}
