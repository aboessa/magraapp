/// كل إسكات قاعدة تحليل له سببٌ مكتوب (`DEBT-102`).
///
/// ## العلّة
///
/// كان `analysis_options.yaml` يُسكِت ستّ قواعد بتعليقٍ واحد يعتذر عن «58 info»
/// سيُصلَحن لاحقًا. الدين سُدِّد ضمنًا في دفعاتٍ سابقة — بإعادة تفعيل الأربع
/// الأسلوبية كانت المحصّلة **مشكلتين** لا 58 — وبقي الإسكات وحده سنةً بلا
/// مراجعة. القاعدة المُسكَتة بلا سبب لا تُعاد أبدًا، لأن أحدًا لا يعرف ثمن
/// إعادتها.
///
/// ## ما يفحصه هذا الحرس
///
/// أن **كل** مدخل تحت `analyzer: errors:` يسبقه تعليق. ولا يفحص جودة السبب —
/// لا يمكن — لكنه يجعل الإسكات الصامت مستحيلًا: من يضيف سطرًا يُطالَب بكتابة
/// سببه في نفس اللحظة، لا في «متابعةٍ» لا تأتي.
///
/// وقائمةُ المسموح **مقصودة**: نموّها يجب أن يكون فعلًا واعيًا يُرى في المراجعة،
/// لا سطرًا يُدَسّ في ملفٍ لا يقرأه أحد.
library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// القواعد المُسكَتة المعروفة، وسببُ كلٍّ منها في `analysis_options.yaml`.
///
/// أيّ إضافة تُفشل هذا الاختبار حتى تُدرَج هنا **وتُشرَح هناك**.
const _knownSuppressions = <String>{
  'invalid_annotation_target',
  'dangling_library_doc_comments',
};

void main() {
  final file = File('analysis_options.yaml');
  final lines = file.readAsLinesSync();

  /// المُسكَتات كما هي في الملف. قراءةُ الأسطر تكفي ولا تستدعي إضافة حزمة
  /// `yaml` لأجل حرسٍ واحد — والتعليقات (وهي نصف المفحوص) تُسقطها أي مُحلِّل.
  Set<String> suppressed() => {
    for (final line in lines)
      if (RegExp(r'^\s+([a-z_]+):\s*ignore\s*$').firstMatch(line)
          case final match?)
        match.group(1)!,
  };

  test('لا قاعدة مُسكَتة خارج القائمة المُعلَنة', () {
    expect(
      suppressed(),
      _knownSuppressions,
      reason:
          'تغيّرت القواعد المُسكَتة. إضافةُ إسكاتٍ تتطلّب سببًا مكتوبًا في '
          '`analysis_options.yaml` وإدراجًا في `_knownSuppressions`؛ وحذفُ '
          'إسكاتٍ (وهو الاتجاه المطلوب) يتطلّب حذفه من هنا.',
    );
  });

  test('كل مدخل إسكات يسبقه تعليق يشرحه', () {
    // فحصٌ على الأسطر لا على الشجرة المُحلَّلة، لأن YAML يُسقط التعليقات —
    // والتعليق هو المقصود بالفحص.
    final missing = <String>[];
    for (var i = 0; i < lines.length; i++) {
      final match = RegExp(r'^\s{4}([a-z_]+):\s*ignore\s*$').firstMatch(lines[i]);
      if (match == null) continue;
      final rule = match.group(1)!;
      final hasReason = i > 0 && lines[i - 1].trimLeft().startsWith('#');
      if (!hasReason) missing.add(rule);
    }

    expect(
      missing,
      isEmpty,
      reason: 'إسكاتٌ بلا سبب مكتوب فوقه مباشرةً: $missing',
    );
  });

  // كان هنا تأكيدٌ ثالث: «نصّ التعليق المُعتذِر لم يعد موجودًا». وأسقطتُه لأنه
  // فشل على **الشرح نفسه**: الملف يقتبس العبارة القديمة ليوثّق ما كان، فحرسٌ
  // يمنع ذكرها يمنع توثيقها. وهذا الفخّ تكرّر في هذا الأودت سبع مرّات، ووقعتُ
  // فيه هنا مرّة أخرى — فالتسجيل أنفع من التكرار: حرسٌ على نصّ المصدر يرصد
  // التعليق الذي يشرح العطل. والخاصّية الحقيقية محفوظة في التأكيدين أعلاه:
  // مجموعة المُسكَتات مُعلَنة، ولكلٍّ سببٌ مكتوب.
}
