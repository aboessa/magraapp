/**
 * مسار لوحة الإدارة في المتصفح.
 *
 * ## لماذا ليس /admin
 *
 * `/admin` أول ما تجرّبه أدوات الفحص الآلي، فتركه يعني سجلات مليئة بمحاولات
 * دخول ونماذج تُستهدف بالتخمين. تغييره إلى مسار غير متوقّع يُسكت أكثر تلك
 * الضوضاء.
 *
 * ## ما هذا وما ليس هو
 *
 * **هذا ليس إجراءً أمنيًا.** حزمة JavaScript عامة، ومن يقرؤها يجد المسار في
 * دقائق. الحماية الحقيقية هي المصادقة في lib/adminSession.ts وحرس
 * requireAdmin في الخادم: بلا جلسة صالحة كل نداء يُرفض بـ401 أيًا كان المسار
 * الذي فُتح منه.
 *
 * قيمة الغموض هنا تقليل الضوضاء لا منع المخترق.
 *
 * ## الفرق بين هذا و/api/v1/admin
 *
 * هذا مسار **المتصفح** فقط. مسارات الـAPI تبقى `/api/v1/admin/*` بلا تغيير،
 * فهي محروسة بالمصادقة لا بالغموض، وتغييرها يكسر كل نداء بلا مقابل.
 */
export const ADMIN_BASE = '/iamnotsite'

/// يبني مسارًا فرعيًا داخل اللوحة: adminPath('series') → '/iamnotsite/series'
export function adminPath(sub = ''): string {
  const clean = sub.replace(/^\/+/, '')
  return clean ? `${ADMIN_BASE}/${clean}` : ADMIN_BASE
}
