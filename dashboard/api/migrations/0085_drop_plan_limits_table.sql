-- API-102: إسقاط `subscription_plan_limits` — مصدر حقيقة ثانٍ لم يقرأه أحد.
--
-- ## ما كان
--
-- الأرقام مُعلَنة في `src/lib/familyPolicy.ts` **وفي** هذا الجدول (المهاجرة
-- 0006). والمفروض فعلًا هو الكود: بحثتُ في `src/` كلّه فلا سطر واحد يقرأ هذا
-- الجدول — لا `FamilyState` الذي يفرض الحدود، ولا `routes/billing.ts` الذي
-- يعرضها، ولا `routes/adminPlans.ts` (وهو يُعلن `source: 'family_policy'` صراحةً).
--
-- ## لماذا الإسقاط لا التحويل إلى مصدر
--
-- موضع الفرض هو الكائن الدائم، بعدٍّ-ثم-إدراج مُسلسَل لكل أسرة. قراءة الحدّ من
-- D1 هناك تُدخل فشلًا شبكيًّا في اللحظة التي يجب أن تكون قاطعة: انقطاع D1 يصير
-- إمّا فتحًا للباب أو منعًا لأسرة تدفع.
--
-- و«تغيير حدّ بلا نشر كود» ليس حاجة قائمة: الحدود قرار تسعير موقوف على
-- `API-104`، وكل تغيير فيها يستحقّ مراجعةً واختبارًا.
--
-- ## ولماذا الإسقاط أهمّ من مجرّد تنظيف
--
-- هذا الجدول **يبدو حيًّا**: أعمدته صحيحة، وصفوفه مزروعة، وفيه `policy_version`
-- — ولم يُدرَج في قائمة الجداول الميتة في `0010_cleanup_dead_d1_tables.sql`. فأي
-- عملية تسويق تُعدّل صفًّا فيه وتظنّ أنها غيّرت حدًّا، والحدّ لا يتغيّر. وفخٌّ
-- صامتٌ كهذا أسوأ من غياب الجدول.
--
-- بديله في الكود: `PLAN_POLICY_VERSION` في `familyPolicy.ts`، مع بصمة للأرقام
-- يثبّتها اختبار فلا يُنسى رفع الإصدار.
--
-- ملاحظة: `DATABASE_V2_SCHEMA.sql` يذكر هذا الجدول بكثافة. ذلك المستند **تصميم
-- Postgres غير مطبَّق** لا مخطَّط D1 الحالي، وإسقاط الجدول هنا لا يمسّه.
DROP TABLE IF EXISTS subscription_plan_limits;
