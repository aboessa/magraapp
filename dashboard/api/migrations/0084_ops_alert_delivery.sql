-- OPS-106: تنبيهات فعلية — إزالة التكرار بنيويًّا، وتسجيل ما وصل فعلًا.
--
-- ## لماذا فهرس فريد جزئي لا فحص في الكود
--
-- `ops_alerts.fingerprint` كان بلا قيد فرادة، فكل دورة فحص تفتح تنبيهًا جديدًا
-- لنفس الحالة: عطلٌ واحد يستمرّ يومًا يُنتج ٢٨٨ صفًّا بفحص كل خمس دقائق، وشاشة
-- العمليات تعرض «٢٨٨ تنبيهًا نشطًا» عن مشكلة واحدة — وهو ضجيج يُدرِّب من يقرأه
-- على تجاهله.
--
-- والفحص في الكود (SELECT ثم INSERT) لا يكفي: دورتان متقاربتان — أو مستهلك DLQ
-- ودورة فحص في اللحظة نفسها — تمرّان من الفحص كلتاهما ثم تُدرجان. القيد في
-- القاعدة هو الشيء الوحيد الذي لا يتجاوزه تزامن.
--
-- **جزئي** عن قصد: الفرادة تلزم للتنبيهات الحيّة وحدها. تنبيه أُغلق ثم عادت
-- حالته بعد شهر يجب أن يكون صفًّا جديدًا بتاريخ جديد — لا إحياءً لصفّ قديم يجعل
-- `started_at` كذبة.
CREATE UNIQUE INDEX IF NOT EXISTS idx_ops_alerts_live_fingerprint
  ON ops_alerts(fingerprint)
  WHERE status IN ('open', 'acknowledged');

-- ## تسجيل التسليم
--
-- التنبيه الذي لا يصل أحدًا ليس تنبيهًا بل صفًّا في جدول. وهذان العمودان يجعلان
-- «هل وصل؟» سؤالًا له جواب مكتوب بدل افتراض:
--
--   * `notified_at` — لحظة نجاح التسليم، أو `NULL` إن لم يُسلَّم.
--   * `notify_outcome` — `sent` أو `unconfigured` أو `provider_error`.
--
-- و`unconfigured` قيمة صريحة لأنها الحالة الأخطر: النظام يعمل، والتنبيهات
-- تُكتب، ولا أحد يستقبلها. تركها `NULL` كان سيخلطها بـ«لم يُحاول بعد».
ALTER TABLE ops_alerts ADD COLUMN notified_at TEXT;
ALTER TABLE ops_alerts ADD COLUMN notify_outcome TEXT;
