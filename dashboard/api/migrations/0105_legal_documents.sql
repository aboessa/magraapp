-- 0105 — legal documents: privacy policy, children's privacy, terms, account deletion.
--
-- One row per document. Edited in the admin «الصفحات القانونية» (`publish`),
-- read publicly by the website (`/legal/:slug`) and the app through
-- `GET /api/v1/legal/:slug`, which returns published documents only.
--
-- The seeded text is a DRAFT written from what the code actually stores and
-- deletes (docs/DATA_RETENTION.md). It is `draft` on purpose: publishing a
-- legal text is the owner's decision after legal review, and the publish route
-- refuses a body that still contains a `{{placeholder}}`.
--
-- `version` increases on every publish, so an accepted version can be recorded.
CREATE TABLE IF NOT EXISTS legal_documents (
  slug TEXT PRIMARY KEY CHECK (slug IN ('privacy', 'children-privacy', 'terms', 'delete-account')),
  title_ar TEXT NOT NULL,
  body_ar TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  version INTEGER NOT NULL DEFAULT 0,
  published_title_ar TEXT,
  published_body_ar TEXT,
  published_at TEXT,
  updated_by TEXT,
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

