-- ‏0097 — يُنهي أحداث الإسقاط الفاشلة التي صار هدفها غير موجود.
--
-- ## الحالة المقيسة
--
-- ‏`failed_family_events` فيه **51 صفًّا `pending`** على الإنتاج، بين
-- 2026-09-03 و2026-09-07، ومحاولةٌ واحدة لكلٍّ. وهي ترفع `dlq:pending` بشدّة
-- `high` كل خمس دقائق — والتنبيه **صادق**: ثمّة أحداث فاشلة لم تُحَل.
--
-- لكن قياسها كشف أنها غير قابلة للحلّ:
--
-- | النوع | العدد | حساباتٌ معنيّة | الحساب ما زال موجودًا |
-- |---|---:|---:|---:|
-- | `playback.started` | 16 | 1 | **0** |
-- | `session.created` | 14 | 1 | **0** |
-- | `playback.ended` | 12 | 1 | **0** |
-- | `progress.updated` | 8 | 1 | **0** |
-- | `content.completed` | 1 | 1 | **0** |
--
-- أي أن الواحد والخمسين كلّها **لحسابٍ واحد حُذف بعدها**. وإعادة تشغيل حدث إسقاط
-- لأسرةٍ لم تبق موجودة ليست مؤجَّلة بل **مستحيلة**: لا حالة تُسقَط عليها.
--
-- ## لماذا `discarded` لا حذفٌ ولا `replayed`
--
-- المخطَّط نفسه يحمل المفردة: `CHECK (status IN ('pending','replayed','discarded'))`
-- مع `resolved_at` و`resolved_by` و`resolution_note`. فـ`discarded` هي الحالة
-- النهائية المقصودة لِما لا يُعاد تشغيله.
--
-- و**لا تُحذَف الصفوف**: هي سجلٌّ بأن إسقاطًا فشل، وحذفه يُخفي أن الفشل حدث.
-- و`replayed` كانت ستكون كذبة — لم يُشغَّل شيء.
--
-- ## القاعدة، لا التنظيف
--
-- الشرط `parent_id NOT IN (SELECT id FROM parents)` هو ما يجعل هذا **قاعدة** لا
-- عملية لمرّة: حدثٌ فاشل لأسرةٍ **قائمة** يبقى `pending` ويبقى يُنبّه — وذلك
-- صحيح، لأنه قابل للإصلاح. فلا يُسكِت هذا الترحيل تنبيهًا يستحقّ أن يُرى.
--
-- و`parent_id IS NOT NULL` شرطٌ ثانٍ: صفٌّ بلا `parent_id` لا نعرف هدفه، فلا
-- يُحكم عليه هنا.
--
-- **ولا-عملية بالإعادة**: `WHERE status = 'pending'` وحده يكفي لذلك.
--
-- ## ما يبقى بعده
--
-- التنبيه يُغلق نفسه: `probeDeadLetterQueue` يرفع `dlq:pending` على
-- `status = 'pending'` وحدها، ويستدعي `clears` حين تصير صفرًا. فلا خطوة يدوية.

UPDATE failed_family_events
   SET status = 'discarded',
       resolved_at = datetime('now'),
       resolved_by = 'migration:0097',
       resolution_note = 'الأسرة الهدف غير موجودة، فالإسقاط غير قابل للتطبيق'
 WHERE status = 'pending'
   AND parent_id IS NOT NULL
   AND parent_id NOT IN (SELECT id FROM parents);
