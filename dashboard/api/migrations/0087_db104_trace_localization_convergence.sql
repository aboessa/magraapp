-- ## الأثر الذي يصلحه هذا الملف
--
-- ترجمة هذه اللعبة مكتوبة **مرّتين** بقيمتين مختلفتين:
--
--   * `0074`  → `game.trace.word.amal`
--   * `0074d` → `game.trace.free`
--
-- وكلتاهما `INSERT OR IGNORE`، فالفائز هو **من وصل أوّلًا** لا من كان صحيحًا.
-- ولمّا كان `0074` يتوقّف قبل صفّه، فازت قيمة `0074d` في كل بيئة قائمة. وبعد
-- الإصلاح تفوز قيمة `0074` في كل بناء نظيف — فتفترق البيئات في صفٍّ واحد.
--
-- والصحيح منهما مُحدَّد لا مُختار: حزمة اللعبة (كما ثبّتها
-- `0081_fix_wave4_truncated_packs.sql`) فيها ثلاثة مستويات مفاتيحها
-- `game.trace.letter.alif` و`game.trace.letter.baa` و`game.trace.word.amal`.
