-- ولا يلمس هذا الملف `0074d`: تعديله لا يُصلح بيئة طبّقته، والقيمة الصحيحة تُثبَّت
-- هنا بعده فتَغلِب في كل مسار. والصياغة `UPDATE` بلا إدراج: إن غاب الصفّ فلا شيء
-- يحدث، ولا قيد مرجعي يُختبر.

