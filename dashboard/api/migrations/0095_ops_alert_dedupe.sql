-- ‏0095 — يطوي تنبيهات العمليات المكرّرة، ليصير `0084` قابلًا للتطبيق.
--
-- ## لماذا هذا الترحيل موجود
--
-- ‏`0084_ops_alert_delivery.sql` يُنشئ فهرسًا فريدًا جزئيًّا على
-- `ops_alerts(fingerprint) WHERE status IN ('open','acknowledged')`، وتعليقه يشرح
-- العطل: محرّك التنبيه **يُدرج** بدل أن يُحدّث، فعطلٌ مستمرّ يُنتج صفًّا كل دورة
-- فحص، «و٢٨٨ تنبيهًا نشطًا عن مشكلة واحدة ضجيجٌ يُدرِّب من يقرأه على تجاهله».
--
-- وتطبيقه على الإنتاج فشل بـ
-- `UNIQUE constraint failed: ops_alerts.fingerprint` — **لأن العطل وقع بالفعل**،
-- والجدول يحمل ما يمنعه الفهرس. المقيس في 2026-09-23:
--
--   * 11,640 صفًّا في `ops_alerts`، منها **11,574 حيًّا**
--   * و**بصمتان فقط** بينها: `dlq:pending` (5,820 صفًّا) و`queue:stale` (5,754)
--   * كلتاهما `high` ومفتوحة منذ **2026-09-03** — عشرون يومًا
--
-- أي أن شاشة العمليات كانت تعرض أحد عشر ألف تنبيه نشط عن **مشكلتين**، وهو بالضبط
-- السبب الذي جعلهما تمرّان عشرين يومًا بلا أن يراهما أحد. فالترحيل الذي يُصلح
-- الضجيج كان محجوبًا بالضجيج نفسه.
--
-- ## القاعدة: يبقى الأقدم لكل بصمة
--
-- `started_at` في الصفّ الباقي يجب أن يكون **لحظة بداية الحالة فعلًا**، لا لحظة
-- آخر دورة فحص. وتعليق `0084` يقول هذا صراحةً حين يُبرّر جزئية الفهرس: «تنبيه
-- أُغلق ثم عادت حالته بعد شهر يجب أن يكون صفًّا جديدًا بتاريخ جديد — لا إحياءً
-- لصفّ قديم يجعل `started_at` كذبة». فالاحتفاظ بالأحدث كان سيُنتج نفس الكذبة.
--
-- والمكرّرات **تُحَل لا تُحذَف**: الصفوف سجلٌّ لما جرى، و`resolved` حالةٌ مشروعة
-- في `CHECK` القائم. والحذف كان سيُخفي أن الضجيج حدث.
--
-- ## الشكل، ولماذا بلا دالّة نافذة
--
-- «حُلّني إن وُجد صفٌّ حيٌّ **أقدم منّي** بنفس البصمة» — استعلام مترابط لا
-- `ROW_NUMBER()`: لا اعتماد على إصدار SQLite في D1، ولا على سلوك العمود الحرّ مع
-- `MIN()` (وهو خصوصية موثَّقة لكنها خصوصية). والنتيجة حتميّة: ناجٍ واحد لكل
-- بصمة، والمعرّف فاصلُ التعادل.
--
-- **ولا-عملية بالإعادة**: بعد التطبيق لا يبقى صفٌّ حيٌّ له أقدمُ منه، فالشرط
-- يُطابق صفرًا.
--
-- ## الفهرس أوّلًا، وهو ليس تحسينًا تجميليًّا
--
-- الاستعلام المترابط على 11,574 صفًّا بلا فهرس مسحٌ متداخل — نحو 134 مليون مقارنة،
-- وD1 يقطع الاستعلام الطويل. والفهرس يبقى بعد الترحيل: محرّك التنبيه يبحث
-- بـ`fingerprint` و`status` في كل دورة.

CREATE INDEX IF NOT EXISTS idx_ops_alerts_fingerprint_status
  ON ops_alerts(fingerprint, status, started_at, id);

UPDATE ops_alerts
   SET status = 'resolved',
       resolved_at = COALESCE(resolved_at, datetime('now')),
       updated_at = datetime('now')
 WHERE status IN ('open', 'acknowledged')
   AND EXISTS (
     SELECT 1
       FROM ops_alerts older
      WHERE older.fingerprint = ops_alerts.fingerprint
        AND older.status IN ('open', 'acknowledged')
        AND (
          older.started_at < ops_alerts.started_at
          OR (older.started_at = ops_alerts.started_at AND older.id < ops_alerts.id)
        )
   );

-- ## ما لا يفعله هذا الترحيل، ومُسمّى عن قصد
--
-- **لا يُصلح المحرّك.** الإدراج المتكرّر يمنعه فهرس `0084`، وهو الترحيل التالي.
-- وهذا يطوي ما تراكم فقط.
--
-- **ولا يُغلق التنبيهين الباقيين**، لأنهما يصفان حالةً قائمة يجب أن تُقرأ:
-- `queue_health` يقول إن `family_events` آخر نجاح له **2026-09-03 20:59:17**
-- وحالته `degraded`، و51 حدثًا في `failed_family_events` بلا حلّ.
--
-- وقراءتها الصحيحة أن الإنتاج فيه **صفر أسرة**: لا أحداث تُنتَج، فالمستهلك لا
-- يعمل، فـ`last_success_at` لا يتقدّم — أي أن المحرّك يُبلّغ «الخمول» على أنه
-- «تدهور». وذلك عطلٌ في دلالة التنبيه لا في الطابور، وسيستمرّ في الإطلاق ما دامت
-- المنصّة قبل الإطلاق. إصلاحه قرارٌ في ماذا يعني `degraded` بلا حِمل، ولم أخترْه
-- هنا.
